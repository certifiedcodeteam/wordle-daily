import assert from "node:assert/strict";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import wordListPath from "word-list";

const require = createRequire(import.meta.url);
const frequencies = require("subtlex-word-frequencies");
const scowl = require("wordlist-english");
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const answerSeedPath = path.join(root, "data/word-lists/answers.txt");
const excludedAnswersPath = path.join(root, "data/word-lists/excluded-answers.txt");
const outputPaths = [
  path.join(root, "src/lib/wordle/words.js"),
  path.join(root, "base44/shared/words.js"),
];

const ANSWER_TARGET = 900;
const WORD_PATTERN = /^[a-z]{5}$/;
const COMMON_SCOWL_TIERS = [10, 20];

function readWords(filePath, { comments = false } = {}) {
  const content = fs.readFileSync(filePath, "utf8");
  const normalized = comments
    ? content.split(/\r?\n/).map((line) => line.replace(/#.*/, "")).join(" ")
    : content;
  return normalized.trim().split(/\s+/).filter(Boolean);
}

function unique(words) {
  return [...new Set(words)];
}

function isLikelySimplePlural(word) {
  return word.endsWith("s") && !word.endsWith("ss") && !word.endsWith("us") && !word.endsWith("is");
}

function formatWords(words) {
  const lines = [];
  for (let index = 0; index < words.length; index += 12) {
    lines.push(words.slice(index, index + 12).join(" "));
  }
  return lines.join("\n");
}

const rawSeedAnswers = readWords(answerSeedPath);
const seedAnswers = unique(rawSeedAnswers);
const excludedAnswers = new Set(readWords(excludedAnswersPath, { comments: true }));
const dictionaryWords = unique(readWords(wordListPath).filter((word) => WORD_PATTERN.test(word))).sort();
const validGuessSet = new Set([...dictionaryWords, ...seedAnswers]);
const commonAnswerPool = new Set(
  COMMON_SCOWL_TIERS.flatMap((tier) => scowl[`english/${tier}`]).filter((word) => WORD_PATTERN.test(word)),
);

const rankedCandidates = frequencies
  .filter(({ word }) => WORD_PATTERN.test(word))
  .map(({ word }) => word)
  .filter((word) => validGuessSet.has(word))
  .filter((word) => commonAnswerPool.has(word))
  .filter((word) => !excludedAnswers.has(word))
  .filter((word) => !isLikelySimplePlural(word));

const answers = [...seedAnswers];
const answerSet = new Set(answers);
for (const word of rankedCandidates) {
  if (answers.length >= ANSWER_TARGET) break;
  if (!answerSet.has(word)) {
    answers.push(word);
    answerSet.add(word);
  }
}

const validGuesses = [...validGuessSet].sort();
const extraGuesses = validGuesses.filter((word) => !answerSet.has(word));

assert.equal(rawSeedAnswers.length, seedAnswers.length, "Seed answers must be unique");
assert.equal(answers.length, ANSWER_TARGET, `Expected ${ANSWER_TARGET} answers`);
assert.ok(answers.every((word) => WORD_PATTERN.test(word)), "Answers must be lowercase five-letter words");
assert.ok(validGuesses.every((word) => WORD_PATTERN.test(word)), "Guesses must be lowercase five-letter words");
assert.ok(answers.every((word) => validGuessSet.has(word)), "Every answer must be a valid guess");

const generated = `// Generated by scripts/generate-word-lists.mjs. Do not edit directly.\n` +
  `// Sources: word-list, SCOWL commonness tiers, SUBTLEX-US frequencies, and local overrides.\n` +
  `export const ANSWERS = \`\n${formatWords(answers)}\n\`.trim().split(/\\s+/);\n\n` +
  `export const EXTRA_GUESSES = \`\n${formatWords(extraGuesses)}\n\`.trim().split(/\\s+/);\n\n` +
  `export const VALID_GUESSES = new Set([...ANSWERS, ...EXTRA_GUESSES]);\n`;

const checkOnly = process.argv.includes("--check");
let drifted = false;

for (const outputPath of outputPaths) {
  if (checkOnly) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== generated) {
      console.error(`${path.relative(root, outputPath)} is out of date. Run npm run words:generate.`);
      drifted = true;
    }
  } else {
    fs.writeFileSync(outputPath, generated);
  }
}

if (drifted) process.exitCode = 1;
else console.log(`${checkOnly ? "Verified" : "Generated"} ${answers.length} answers and ${validGuesses.length} valid guesses.`);
